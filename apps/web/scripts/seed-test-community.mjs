/**
 * TEST-COMMUNITY seed CLI (pre-launch test phase). Drives the fake-member
 * seeder at POST /api/admin/seed/test-community (CRON_SECRET service scope)
 * and writes the generated logins README to TEST-COMMUNITY-LOGINS.md at the
 * repo root — the single place every test account is documented (the shared
 * password is never written out; it is the TEST_COMMUNITY_PASSWORD env value).
 *
 * NEVER run against the production database. The route refuses any target that
 * is not a verified non-production database (apps/web/src/lib/seed/target-guard.ts):
 * the production project ref (the Supabase project labelled "Dev Xidig App",
 * tbdryvhxxiqadseuxclm — the live xidig.net DB) is refused whatever NODE_ENV
 * the server runs with, and an undeterminable target fails closed. History: the
 * old NODE_ENV-only guard let this dataset reach production (12 Sep 2026 audit).
 * The dataset is fake people by design; every account is marked users.is_test.
 *
 * Usage (dev server must be running):
 *   CRON_SECRET=... APP_URL=http://localhost:3000 node apps/web/scripts/seed-test-community.mjs
 *   CRON_SECRET=... APP_URL=http://localhost:3000 node apps/web/scripts/seed-test-community.mjs --reset
 *
 * Or via pnpm:  pnpm --filter @xidig/web seed:test-community   [-- --reset]
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP_URL = process.env.APP_URL ?? 'http://localhost:3000';
const CRON_SECRET = process.env.CRON_SECRET ?? '';
const reset = process.argv.includes('--reset');

if (!CRON_SECRET) {
  console.error('✗ CRON_SECRET is required (it authorises the seed job). Set it and retry.');
  process.exit(1);
}

const url = `${APP_URL.replace(/\/$/, '')}/api/admin/seed/test-community`;
const method = reset ? 'DELETE' : 'POST';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const readmePath = resolve(repoRoot, 'TEST-COMMUNITY-LOGINS.md');

function renderReadme(summary) {
  const rows = summary.logins
    .map(
      (l) =>
        `| \`${l.email}\` | ${l.displayName} | \`${l.handle}\` | ${l.role} | ${l.tier} | ${l.status} | ${l.language} | ${l.purpose} |`,
    )
    .join('\n');
  return `# Test-community logins (pre-launch test phase)

> **Generated by \`pnpm --filter @xidig/web seed:test-community\`** — do not edit by hand.
> Re-running the seeder regenerates this file. Reset with \`-- --reset\`.

- **Password for EVERY account:** the value of \`TEST_COMMUNITY_PASSWORD\` /
  \`XIDIG_TEST_COMMUNITY_PASSWORD\` in the seeding environment. It is deliberately
  NOT written to this file or returned by the API. Re-running the seeder resets
  every existing test account to the configured value.
- **Email convention:** \`<handle>@example.com\` — the handle IS the login.
- Seed label: \`${summary.label}\` · users created: ${summary.usersCreated} · already existed: ${summary.usersExisting} · content seeded this run: ${summary.contentSeeded}
- The standard AI actor \`xidig_ai\` also exists (provisioned passwordlessly — not a login account).
- Full persona/design documentation: \`docs/test-community.md\`.
- Ordered screenshot/demo walkthrough: \`docs/test-community-tour.md\`.

## Accounts

| Email (login) | Name | Handle | Role | Tier | Status | Lang | What this account tests |
| --- | --- | --- | --- | --- | --- | --- | --- |
${rows}

## Quick tour (good first logins)

- \`warsame_admin@example.com\` — admin dashboards, mod queue, seed admin, pinning.
- \`hodan_mod@example.com\` — reports queue (open/in-review/resolved), HITL Somali lane, appeals.
- \`ayaan_dev@example.com\` — power user: Lab lead, candidate, mentions, credited answers.
- \`khalid_codes@example.com\` — Somali UI + low-bandwidth mode + unread DMs from a mentee's view.
- \`xasan_beero@example.com\` — Somali-only rural farmer, low bandwidth, club member.
- \`safiya_aragto@example.com\` — pure lurker: following feed + notification inbox.
- \`tuute_cusub@example.com\` — day-zero empty state + onboarding + AI welcome DM request.
- \`burhaan_qaylo@example.com\` — SUSPENDED account (login blocked/limited by design).
- \`caawiye_ai@example.com\` / \`warshad_ai@example.com\` — labelled AI helpers (is_ai badge).

## Seeded run counts

\`\`\`json
${JSON.stringify(summary.counts, null, 2)}
\`\`\`
`;
}

try {
  const res = await fetch(url, {
    method,
    headers: { authorization: `Bearer ${CRON_SECRET}` },
  });
  const body = await res.json().catch(() => ({}));
  if (!res.ok) {
    const refusal = body?.seedTarget;
    if (refusal) {
      console.error(`✗ Refused: ${refusal.detail}`);
      console.error('  The seeder only writes to a verified non-production database (lib/seed/target-guard.ts).');
    } else {
      console.error(`✗ Test-community ${method} failed (${res.status}):`, JSON.stringify(body));
    }
    process.exit(1);
  }
  const summary = body.data?.summary ?? body.summary;
  if (reset) {
    console.log('✓ Test-community reset complete:', JSON.stringify(summary, null, 2));
  } else {
    console.log(
      `✓ Test-community seed complete: ${summary.usersCreated} created, ${summary.usersExisting} existing, content seeded: ${summary.contentSeeded}`,
    );
    writeFileSync(readmePath, renderReadme(summary));
    console.log(`✓ Logins README written to ${readmePath}`);
    console.log('  Password for all accounts: the TEST_COMMUNITY_PASSWORD value (never written out).');
  }
} catch (err) {
  console.error(`✗ Could not reach ${url} — is the server running?`, err?.message ?? err);
  process.exit(1);
}
